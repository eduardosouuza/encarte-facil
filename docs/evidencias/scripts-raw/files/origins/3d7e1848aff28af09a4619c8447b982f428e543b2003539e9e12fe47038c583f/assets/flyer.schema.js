import { z } from "zod";
export const elementSchema = z.object({
    id: z.string().max(120).optional(),
    elementId: z.string().max(120).optional(),
    category: z.string().max(40).optional(),
    type: z.string().max(40).optional(),
    subtype: z.string().max(40).optional(),
    x: z.number().finite().optional(),
    y: z.number().finite().optional(),
    width: z.number().finite().nonnegative().optional(),
    height: z.number().finite().nonnegative().optional(),
    rotation: z.number().finite().optional(),
    scaleX: z.number().finite().optional(),
    scaleY: z.number().finite().optional(),
    opacity: z.number().finite().min(0).max(1).optional(),
    zIndex: z.number().int().optional(),
    text: z.string().max(4000).optional(),
    backgroundColor: z.string().max(32).optional(),
    image: z.string().max(2000).optional(),
    asset: z.string().max(2000).optional(),
    textStyle: z
        .object({
        fontFamily: z.string().max(120).optional(),
        fontWeight: z.union([z.number(), z.string()]).optional(),
        fontSize: z.number().finite().optional(),
        color: z.string().max(32).optional(),
        align: z.enum(["left", "center", "right"]).optional(),
        textDecoration: z.string().max(40).optional(),
        fontStyle: z.string().max(40).optional(),
    })
        .optional(),
});
export const flyerProductSchema = z.object({
    id: z.string().max(120).optional(),
    productId: z.string().max(120).optional(),
    name: z.string().max(160).optional(),
    image: z.string().max(2000).optional(),
    price: z.number().finite().nonnegative().optional(),
    salePrice: z.number().finite().nonnegative().nullable().optional(),
    unit: z.string().max(40).optional(),
    notes: z.string().max(500).optional(),
    x: z.number().finite().optional(),
    y: z.number().finite().optional(),
    width: z.number().finite().nonnegative().optional(),
    height: z.number().finite().nonnegative().optional(),
    rotation: z.number().finite().optional(),
    isHighlighted: z.boolean().optional(),
    tagColor: z.string().max(32).optional(),
    textColor: z.string().max(32).optional(),
    backgroundColor: z.string().max(32).optional(),
    tagShape: z.enum(["circle", "pill", "ticket", "burst", "square"]).optional(),
    tagStyle: z.enum(["solid", "outline", "gradient", "shadow"]).optional(),
});
export const flyerPayloadSchema = z.object({
    name: z.string().trim().min(1, "Informe o nome do encarte").max(160),
    content: z.enum(["flyer", "poster", "shelf_label", "video"]).default("flyer"),
    status: z.enum(["draft", "approved", "published", "archived"]).default("draft"),
    format: z.string().max(60).nullable().optional(),
    design: z.string().max(60).nullable().optional(),
    palette: z.array(z.string().max(32)).max(24).default([]),
    backgroundColor: z.string().max(32).default("#ffffff"),
    startAt: z.string().max(40).nullable().optional(),
    endAt: z.string().max(40).nullable().optional(),
    template: z.boolean().default(false),
    public: z.boolean().default(false),
    elements: z.array(elementSchema).max(400).default([]),
    products: z.array(flyerProductSchema).max(400).default([]),
    footer: z
        .object({
        visible: z.boolean().default(true),
        elements: z.array(z.string().max(200)).max(20).default([]),
    })
        .default({ visible: true, elements: [] }),
    grid: z.record(z.string(), z.unknown()).nullable().optional(),
    gridHighlights: z.record(z.string(), z.unknown()).nullable().optional(),
    settings: z.record(z.string(), z.unknown()).default({}),
    pageSettings: z.record(z.string(), z.unknown()).default({}),
});
export const flyerListQuerySchema = z.object({
    term: z.string().trim().max(120).optional(),
    format: z.string().trim().max(60).optional(),
    status: z.string().trim().max(40).optional(),
    template: z.enum(["true", "false"]).optional(),
    limit: z.coerce.number().int().min(1).max(200).default(20),
    offset: z.coerce.number().int().min(0).default(0),
});
